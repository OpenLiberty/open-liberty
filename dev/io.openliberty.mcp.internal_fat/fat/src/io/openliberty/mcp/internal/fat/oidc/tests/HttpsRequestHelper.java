package io.openliberty.mcp.internal.fat.oidc.tests;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertNotNull;

import java.io.File;
import java.io.FileInputStream;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.net.http.HttpResponse.BodyHandlers;
import java.security.KeyStore;
import java.security.SecureRandom;
import java.security.cert.Certificate;

import javax.net.ssl.SSLContext;
import javax.net.ssl.TrustManagerFactory;

import org.json.JSONObject;

import componenttest.topology.impl.LibertyServer;

/**
 * HTTPS certificate helpers and HTTPS request utilities for the Keycloak testcontainer.
 *
 * <p>This utility class provides:
 * <ol>
 * <li><b>Certificate setup</b> — {@link #buildLibertyAndKeycloakHttpClient} builds an
 * {@link HttpClient} that trusts both the Keycloak self-signed certificate and the
 * Liberty server's auto-generated TLS certificate.</li>
 * <li><b>HTTPS MCP calls</b> — {@link #postMcpHttps} POSTs a JSON-RPC body directly to
 * the Liberty MCP HTTPS endpoint.</li>
 * <li><b>HTTPS JSON fetch</b> — {@link #fetchJsonHttps} GETs a JSON document over any
 * {@code https://} URL in the discovery chain (Liberty or Keycloak).</li>
 * <li><b>HTTPS discovery</b> — {@link #discoverTokenEndpointHttps} runs the full RFC 9728
 * discovery flow over TLS and returns the token endpoint URL.</li>
 * </ol>
 *
 * <p><b>Certificate sources:</b>
 * <ul>
 * <li><b>Keycloak cert</b> — generated at container construction time and held in
 * {@link KeycloakContainer}'s truststore via {@link KeycloakContainer#getOrCreateTruststore()}.</li>
 * <li><b>Liberty cert</b> — auto-generated by Liberty on first start and stored at
 * {@code <serverRoot>/resources/security/key.p12} with password {@code "keypass"}
 * as declared in {@code server.xml}. Must be read <em>after</em> the server starts.</li>
 * </ul>
 *
 * <p>All methods in this class must be called after {@code server.startServer()} so that
 * {@code key.p12} exists on disk.
 */
public final class HttpsRequestHelper {

    // -------------------------------------------------------------------------
    // Certificate setup
    // -------------------------------------------------------------------------

    /**
     * Returns a {@link HttpClient} that trusts both the Keycloak self-signed certificate
     * and the Liberty server's auto-generated TLS certificate.
     *
     * <p>Use this client in HTTPS tests to POST to the Liberty MCP endpoint and to
     * follow {@code https://} discovery URLs that point to either Liberty
     * (e.g. {@code resource_metadata}) or Keycloak (e.g. AS metadata, token endpoint).
     *
     * <p>Must be called after the Liberty server has started.
     *
     * @param keycloakContainer the running Keycloak container
     * @param libertyServer the started Liberty server
     * @return a {@link HttpClient} trusting both certificates
     * @throws Exception if either keystore cannot be read or the SSL context cannot be built
     */
    public static HttpClient buildLibertyAndKeycloakHttpClient(KeycloakContainer keycloakContainer,
                                                               LibertyServer libertyServer)
                    throws Exception {
        SSLContext sslContext = buildCombinedSslContext(keycloakContainer, libertyServer);
        return HttpClient.newBuilder()
                         .sslContext(sslContext)
                         .build();
    }

    // -------------------------------------------------------------------------
    // HTTPS request helpers
    // -------------------------------------------------------------------------

    /**
     * POSTs a JSON-RPC body to the Liberty MCP endpoint over HTTPS.
     *
     * @param server the Liberty server (used to resolve hostname and HTTPS port)
     * @param mcpPath the full context-root + MCP path, e.g. {@code "/oidcAuthFlowTests/mcp"}
     * @param httpClient the {@link HttpClient} returned by {@link #buildLibertyAndKeycloakHttpClient}
     * @param jsonBody the JSON-RPC request body
     * @param bearerToken the Bearer token to include, or {@code null} for an unauthenticated call
     * @param expectedStatus the HTTP status code that must be returned
     * @return the full {@link HttpResponse}
     * @throws Exception if the request fails or the response status does not match
     */
    public static HttpResponse<String> postMcpHttps(LibertyServer server, String mcpPath, HttpClient httpClient,
                                                    String jsonBody, String bearerToken, int expectedStatus)
                    throws Exception {
        String url = "https://" + server.getHostname() + ":" + server.getHttpDefaultSecurePort() + mcpPath;

        HttpRequest.Builder builder = HttpRequest.newBuilder()
                                                 .uri(URI.create(url))
                                                 .header(HttpRequestHelper.HEADER_ACCEPT, HttpRequestHelper.VALUE_ACCEPT)
                                                 .header(HttpRequestHelper.HEADER_MCP_VERSION, HttpRequestHelper.VALUE_MCP_VERSION)
                                                 .header(HttpRequestHelper.HEADER_CONTENT_TYPE, HttpRequestHelper.VALUE_JSON)
                                                 .POST(HttpRequest.BodyPublishers.ofString(jsonBody));
        if (bearerToken != null) {
            builder.header("Authorization", "Bearer " + bearerToken);
        }

        HttpResponse<String> response = httpClient.send(builder.build(), BodyHandlers.ofString());
        if (response.statusCode() != expectedStatus) {
            System.out.println("[KeycloakHttpsContainer] postMcpHttps(" + url + ") -> HTTP "
                               + response.statusCode() + " (expected " + expectedStatus + ")\nBody: " + response.body());
        }
        assertEquals("Unexpected HTTP status from HTTPS MCP call", expectedStatus, response.statusCode());
        return response;
    }

    /**
     * GETs a JSON document using an {@link HttpClient} that trusts both the Liberty and
     * Keycloak self-signed certificates. Use this for any {@code https://} URL in the
     * discovery chain — whether it points to Liberty (resource_metadata) or Keycloak
     * (AS metadata, token endpoint).
     *
     * @param url the URL to fetch
     * @param httpClient the {@link HttpClient} returned by {@link #buildLibertyAndKeycloakHttpClient}
     * @return the parsed JSON response body
     * @throws Exception if the request fails or the response status is not 200
     */
    public static JSONObject fetchJsonHttps(String url, HttpClient httpClient) throws Exception {
        HttpRequest request = HttpRequest.newBuilder()
                                         .uri(URI.create(url))
                                         .header(HttpRequestHelper.HEADER_ACCEPT, HttpRequestHelper.VALUE_JSON)
                                         .GET()
                                         .build();
        HttpResponse<String> response = httpClient.send(request, BodyHandlers.ofString());
        if (response.statusCode() != 200) {
            System.out.println("[KeycloakHttpsContainer] fetchJsonHttps(" + url + ") -> HTTP "
                               + response.statusCode() + "\nBody: " + response.body());
        }
        assertEquals("Expected HTTP 200 from " + url, 200, response.statusCode());
        return new JSONObject(response.body());
    }

    /**
     * Runs the full RFC 9728 discovery flow over HTTPS and returns the
     * {@code token_endpoint} URL from the Authorization Server Metadata.
     *
     * <ol>
     * <li>POSTs an unauthenticated MCP request to get a 401 + {@code WWW-Authenticate}</li>
     * <li>Extracts the {@code resource_metadata} URL and fetches the Protected Resource Metadata</li>
     * <li>Reads {@code authorization_servers[0]} and fetches the AS Metadata</li>
     * <li>Returns the {@code token_endpoint}</li>
     * </ol>
     *
     * @param toolName the name of the MCP tool to call in the initial unauthenticated request
     * @param server the Liberty server
     * @param mcpPath the full context-root + MCP path, e.g. {@code "/oidcAuthFlowTests/mcp"}
     * @param httpClient the {@link HttpClient} returned by {@link #buildLibertyAndKeycloakHttpClient}
     * @return the {@code token_endpoint} URL
     * @throws Exception if any step in the discovery chain fails
     */
    public static String discoverTokenEndpointHttps(String toolName, LibertyServer server,
                                                    String mcpPath, HttpClient httpClient)
                    throws Exception {
        HttpResponse<String> authChallenge = postMcpHttps(server, mcpPath, httpClient,
                                                          HttpRequestHelper.toolCallRequest(toolName), null, 401);

        String resourceMetadataUrl = HttpRequestHelper.extractResourceMetadataUrl(
                                                                                        authChallenge.headers().firstValue("WWW-Authenticate").orElse(null));
        assertNotNull("resource_metadata URL must be present in WWW-Authenticate header", resourceMetadataUrl);

        JSONObject resourceMetadata = fetchJsonHttps(resourceMetadataUrl, httpClient);
        String authorizationServerUrl = resourceMetadata.getJSONArray("authorization_servers").getString(0);
        System.out.println("[KeycloakHttpsContainer] discoverTokenEndpointHttps: authorization_servers[0] = " + authorizationServerUrl);

        JSONObject asMetadata = fetchJsonHttps(authorizationServerUrl + HttpRequestHelper.AS_METADATA_SUFFIX, httpClient);
        String tokenEndpoint = asMetadata.getString("token_endpoint");
        assertNotNull("token_endpoint must be present in AS metadata", tokenEndpoint);
        return tokenEndpoint;
    }

    // Private certificate helpers

    /**
     * Builds an {@link SSLContext} that trusts both the Keycloak self-signed certificate
     * and the Liberty server's auto-generated certificate.
     */
    private static SSLContext buildCombinedSslContext(KeycloakContainer keycloakContainer,
                                                      LibertyServer libertyServer)
                    throws Exception {
        KeyStore combinedTruststore = KeyStore.getInstance("pkcs12");
        combinedTruststore.load(null, null);

        // Add the Keycloak certificate(s)
        KeyStore keycloakTs = keycloakContainer.getOrCreateTruststore();
        java.util.Enumeration<String> keycloakAliases = keycloakTs.aliases();
        while (keycloakAliases.hasMoreElements()) {
            String alias = keycloakAliases.nextElement();
            combinedTruststore.setCertificateEntry("keycloak-" + alias, keycloakTs.getCertificate(alias));
        }

        // Add the Liberty server certificate(s) from its auto-generated key.p12
        KeyStore libertyKeystore = loadLibertyKeystore(libertyServer);
        java.util.Enumeration<String> libertyAliases = libertyKeystore.aliases();
        while (libertyAliases.hasMoreElements()) {
            String alias = libertyAliases.nextElement();
            Certificate cert = libertyKeystore.getCertificate(alias);
            if (cert != null) {
                combinedTruststore.setCertificateEntry("liberty-" + alias, cert);
            }
        }

        TrustManagerFactory tmf = TrustManagerFactory.getInstance("PKIX");
        tmf.init(combinedTruststore);

        SSLContext sslContext = SSLContext.getInstance("TLS");
        sslContext.init(null, tmf.getTrustManagers(), new SecureRandom());
        return sslContext;
    }

    /**
     * Loads Liberty's auto-generated PKCS12 keystore from
     * {@code <serverRoot>/resources/security/key.p12} using the password {@code "keypass"}
     * as declared in {@code server.xml}.
     */
    private static KeyStore loadLibertyKeystore(LibertyServer libertyServer) throws Exception {
        String keyStorePath = libertyServer.getServerRoot() + "/resources/security/key.p12";
        File keyStoreFile = new File(keyStorePath);
        if (!keyStoreFile.exists()) {
            throw new RuntimeException("Liberty keystore not found at: " + keyStorePath
                                       + " — ensure the server has started before calling this method.");
        }
        KeyStore keystore = KeyStore.getInstance("pkcs12");
        try (FileInputStream fis = new FileInputStream(keyStoreFile)) {
            keystore.load(fis, "keypass".toCharArray());
        }
        return keystore;
    }
}
