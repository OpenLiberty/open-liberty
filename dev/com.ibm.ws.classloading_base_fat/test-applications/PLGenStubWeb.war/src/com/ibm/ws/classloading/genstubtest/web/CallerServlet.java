package com.ibm.ws.classloading.genstubtest.web;

import java.io.IOException;

import jakarta.ejb.EJB;
import jakarta.servlet.ServletException;
import jakarta.servlet.annotation.WebServlet;
import jakarta.servlet.http.HttpServlet;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;

import com.ibm.ws.classloading.genstubtest.view.CallerBeanLocal;
import com.ibm.ws.classloading.genstubtest.view.EndpointBeanRemote;

/**
 * This servlet injects an instance of a remote EJB and then attempts to
 * call it when invoked.  The remote interface of the EJB exists in this
 * servlet's WAR file AND in the EJB JAR file, so the interface could be
 * loaded twice - once by the WAR classloader and once by the EAR loader.
 * If the stub class for the EJB was loaded by the EAR loader and not
 * generated by the WAR loader (in a parentLast configuration), then the
 * injection engine would not be able to narrow the stub to this module's
 * remote interface (due to a ClassCastException) - and the remote
 * reference would be null.
 */
@WebServlet("/CallerServlet")
public class CallerServlet extends HttpServlet {
        private static final long serialVersionUID = 1L;

        @EJB
        CallerBeanLocal local;

        @EJB
        EndpointBeanRemote remote;

        /**
         * @see HttpServlet#doGet(HttpServletRequest request, HttpServletResponse response)
         */
        @Override
        protected void doGet(HttpServletRequest request, HttpServletResponse response) throws ServletException, IOException {
                if (local == null) {
                        response.getWriter().append("CallerServlet local reference is null...");
                } else {
                        String s = local.invokeHelloOnEndpoint();
                        response.getWriter().append("CallerServlet CallerEJB returned: " + s);

                        if (remote == null) {
                                response.getWriter().append("CallerServlet remote reference is null");
                        } else {
                                response.getWriter().append("CallerServlet Obtained from endpoint: " + remote.hello());
                        }
                }
                response.getWriter().flush();
                response.getWriter().close();
        }

}
