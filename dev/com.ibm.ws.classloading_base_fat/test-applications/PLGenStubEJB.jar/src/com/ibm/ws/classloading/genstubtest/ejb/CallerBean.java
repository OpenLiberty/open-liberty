package com.ibm.ws.classloading.genstubtest.ejb;

import jakarta.ejb.EJB;
import jakarta.ejb.Local;
import jakarta.ejb.Stateless;

import com.ibm.ws.classloading.genstubtest.view.CallerBeanLocal;
import com.ibm.ws.classloading.genstubtest.view.EndpointBeanRemote;

/**
 * This EJB obtains a reference to a remote EJB using a remote interface
 * packaged in this EJB JAR module.  The same remote interface is also
 * packaged in the WAR module in the same app.  In all cases (parentFirst
 * or parentLast), this EJB should be able to successfully inject the
 * remote stub and execute it.  In parentLast config, the servlet might
 * incorrectly use the stub class generated by the EAR's classloader
 * which would result in a ClassCastException.
 */
@Stateless
@Local(CallerBeanLocal.class)
public class CallerBean implements CallerBeanLocal {


    @EJB
    EndpointBeanRemote remote;

    @Override
    public String invokeHelloOnEndpoint() {
        String s = remote.hello();
        System.out.println("CallerBean.postConstruct - remote->" + s);
        return s;
    }
}
