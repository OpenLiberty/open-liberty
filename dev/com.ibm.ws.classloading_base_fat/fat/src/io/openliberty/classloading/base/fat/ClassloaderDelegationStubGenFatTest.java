package io.openliberty.classloading.base.fat;

import static org.junit.Assert.assertTrue;

import java.io.IOException;
import java.net.URL;

import org.jboss.shrinkwrap.api.ShrinkWrap;
import org.jboss.shrinkwrap.api.spec.EnterpriseArchive;
import org.jboss.shrinkwrap.api.spec.JavaArchive;
import org.jboss.shrinkwrap.api.spec.WebArchive;
import org.junit.BeforeClass;
import org.junit.Test;

import com.ibm.websphere.simplicity.ShrinkHelper;
import com.ibm.websphere.simplicity.ShrinkHelper.DeployOptions;

import componenttest.annotation.AllowedFFDC;
import componenttest.topology.impl.LibertyServer;
import componenttest.topology.impl.LibertyServerFactory;
import componenttest.topology.utils.HttpUtils;

/**
 * Tests for classloader delegation wrt generating stub classes.
 * All tests follow the same format. A unique URL for each test returns either
 * success or a message containing the test failure
 */
@org.junit.runner.RunWith(componenttest.custom.junit.runner.FATRunner.class)
public class ClassloaderDelegationStubGenFatTest {

    private static final String PL_GEN_STUB_EAR = "PLGenStub";

    private static final LibertyServer stubGenPLServer = LibertyServerFactory.getLibertyServer("classloader_stubgen");

    @BeforeClass
    public static void beforeClass() throws Exception {
        JavaArchive ejbJar = ShrinkHelper.buildJavaArchive("PLGenStubEJB.jar",
            "com.ibm.ws.classloading.genstubtest.ejb",
            "com.ibm.ws.classloading.genstubtest.view");
        // Do NOT include genstubtest.view in the WAR: with parentLast delegation the WAR would load
        // its own CallerBeanLocal which is incompatible with the EJB container's version of the same
        // class, causing CWNEN0074E.  CallerBeanLocal must come only from the EJB jar via the parent.
        WebArchive webWar = ShrinkHelper.buildDefaultApp("PLGenStubWeb.war",
            "com.ibm.ws.classloading.genstubtest.web");
        EnterpriseArchive ear = ShrinkWrap.create(EnterpriseArchive.class, PL_GEN_STUB_EAR + ".ear")
            .addAsModule(webWar)
            .addAsModule(ejbJar);
        ShrinkHelper.exportAppToServer(stubGenPLServer, ear, DeployOptions.SERVER_ONLY);
    }

    /**
     * This test verifies that when an EJB's remote interface is in both the EJB module (EAR loader)
     * and the WAR module (WAR loader - child of the EAR loader), that it is correctly generated in both
     * places when using parentLast delegation.  This prevents a ClassCastException in the case where the
     * WAR module attempts to load the stub - if the WAR uses the stub generated by the EAR loader, it will
     * get a CCE.  This test ensures that we can load the stub with the appropriate loader from both modules.
     */
    @Test
    @AllowedFFDC("org.omg.CosNaming.NamingContextPackage.AlreadyBound")
    public void testStubGeneratedInChildLoaderInParentLastDelegation() throws Exception {
        try {
            stubGenPLServer.addInstalledAppForValidation(PL_GEN_STUB_EAR);
            stubGenPLServer.startServer();
            stubGenPLServer.waitForStringInLog("CWWKZ0001I.*"+PL_GEN_STUB_EAR);
            String result = test(stubGenPLServer, "/PLGenStubWeb/CallerServlet");
            // This first assert assures that the stub can be generated/loaded from the app loader when invoked
            // from the app loader (from an EJB in it's own module).
            assertTrue("Unable to access remote endpoint EJB via local EJB", result.contains("CallerServlet CallerEJB returned: Hello"));
            // This second assert assures that the stub can be generated/loaded from the war loader when invoked
            // from that module's loader (from a servlet).  If the war loader delegated to the app loader, this would
            // fail.
            assertTrue("Unable to access remote endpoint EJB directly from Web module", result.contains("CallerServlet Obtained from endpoint: Hello"));
        } finally {
            stubGenPLServer.stopServer("CWWKS9582E"); // intermittent SSL error not related to test case
        }

    }

    private String test(LibertyServer server, String testUri) throws IOException {
        URL url = new URL("http://" + server.getHostname() + ":" + server.getHttpDefaultPort() + testUri);
        return HttpUtils.getHttpResponseAsString(url);
    }

}
